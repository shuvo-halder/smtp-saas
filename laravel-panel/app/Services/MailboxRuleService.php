<?php

namespace App\Services;

use App\Models\EmailAlias;
use App\Models\Mailbox;
use Illuminate\Support\Facades\Log;

class MailboxRuleService
{
    /**
     * Compile an RFC 5228, RFC 5230, RFC 3894 compliant Sieve script for the mailbox.
     */
    public function compileSieveScript(Mailbox $mailbox): string
    {
        $requires = ['fileinto', 'vacation', 'date', 'relational', 'copy'];
        $requireLine = 'require ["' . implode('", "', $requires) . '"];';

        $timestamp = now()->toIso8601String();
        $script = <<<SIEVE
# =============================================================================
# Dovecot Sieve Filter Rules generated by EmailSaaS
# Mailbox: {$mailbox->email}
# Generated: {$timestamp}
# =============================================================================

{$requireLine}

SIEVE;

        // 1. Mailbox Forwarding Rules
        if ($mailbox->is_forwarding_enabled) {
            $destinations = $mailbox->getForwardingDestinationsList();
            if (!empty($destinations)) {
                $script .= "\n# ─── Inbound Forwarding ────────────────────────────────────────────────────────\n";
                foreach ($destinations as $dest) {
                    $escapedDest = addcslashes($dest, '"\\');
                    if ($mailbox->forwarding_keep_copy) {
                        $script .= "redirect :copy \"{$escapedDest}\";\n";
                    } else {
                        $script .= "redirect \"{$escapedDest}\";\n";
                    }
                }
                if (!$mailbox->forwarding_keep_copy) {
                    $script .= "stop;\n";
                }
            }
        }

        // 2. Auto-Reply (Vacation / Out-of-Office)
        if ($mailbox->auto_reply_enabled && !empty($mailbox->auto_reply_subject) && !empty($mailbox->auto_reply_body)) {
            $script .= "\n# ─── Out-of-Office Auto-Reply ──────────────────────────────────────────────────\n";

            $conditions = [
                'not header :contains "Precedence" ["bulk", "list", "junk"]',
                'not header :contains "Auto-Submitted" ["auto-generated", "auto-replied"]',
                'not exists "List-Id"',
                'not header :matches "Return-Path" "<>"',
            ];

            if ($mailbox->auto_reply_start_at) {
                $startIso = $mailbox->auto_reply_start_at->toIso8601ZuluString();
                $conditions[] = "currentdate :value \"ge\" \"iso8601\" \"{$startIso}\"";
            }

            if ($mailbox->auto_reply_end_at) {
                $endIso = $mailbox->auto_reply_end_at->toIso8601ZuluString();
                $conditions[] = "currentdate :value \"le\" \"iso8601\" \"{$endIso}\"";
            }

            $condStr = implode(",\n    ", $conditions);
            $escapedSubject = addcslashes($mailbox->auto_reply_subject, '"\\');
            $cleanBody = strip_tags($mailbox->auto_reply_body);
            $escapedBody = addcslashes($cleanBody, '"\\');

            $script .= <<<SIEVE
if allof (
    {$condStr}
) {
    vacation
        :days 1
        :subject "{$escapedSubject}"
        "{$escapedBody}";
}

SIEVE;
        }

        $script .= "\n# ─── Default Delivery ──────────────────────────────────────────────────────────\n";
        $script .= "keep;\n";

        return $script;
    }

    /**
     * Synchronize Sieve script to disk if mail storage is mounted
     */
    public function syncSieveScript(Mailbox $mailbox): bool
    {
        $scriptContent = $this->compileSieveScript($mailbox);

        $domain = $mailbox->domain?->domain_name;
        if (!$domain) {
            return false;
        }

        // Possible home directory locations
        $candidateDirs = [
            "/var/vmail/{$domain}/{$mailbox->local_part}",
            "/var/mail/vhosts/{$domain}/{$mailbox->local_part}",
        ];

        $targetDir = null;
        foreach ($candidateDirs as $dir) {
            if (is_dir($dir)) {
                $targetDir = $dir;
                break;
            }
        }

        if ($targetDir && is_writable($targetDir)) {
            $sieveFile = $targetDir . '/.dovecot.sieve';
            $tmpFile = $sieveFile . '.tmp.' . uniqid();
            if (file_put_contents($tmpFile, $scriptContent) !== false) {
                @chmod($tmpFile, 0600);
                if (rename($tmpFile, $sieveFile)) {
                    Log::info("MailboxRuleService: Synced Sieve script for {$mailbox->email} to {$sieveFile}");
                    return true;
                }
                @unlink($tmpFile);
            }
        }

        Log::info("MailboxRuleService: Sieve script compiled for {$mailbox->email} (stored in database/memory, disk sync bypassed in local environment)");
        return true;
    }

    /**
     * Detect direct and multi-hop circular forwarding loops across mailboxes and aliases.
     *
     * @param string $sourceEmail The email address being configured
     * @param string[] $destinationEmails Array of destination emails to check
     * @param int|null $currentMailboxId Mailbox ID to exclude from self-querying
     * @return array{has_cycle: bool, cycle_path: string|null, error: string|null}
     */
    public function detectForwardingCycle(string $sourceEmail, array $destinationEmails, ?int $currentMailboxId = null): array
    {
        $source = strtolower(trim($sourceEmail));

        foreach ($destinationEmails as $rawDest) {
            $dest = strtolower(trim($rawDest));

            // 1. Direct self-forwarding check
            if ($dest === $source) {
                return [
                    'has_cycle'  => true,
                    'cycle_path' => "{$source} -> {$dest}",
                    'error'      => "Self-forwarding loop detected: mailbox {$source} cannot forward to itself.",
                ];
            }

            // 2. Multi-hop circular forwarding chain check
            $visited = [
                $source => true,
                $dest   => true,
            ];
            $path = [$source, $dest];
            $current = $dest;
            $maxHops = 30;
            $hops = 0;

            while ($hops < $maxHops) {
                $hops++;

                // Check if $current has an active forwarding mailbox
                $nextMailboxQuery = Mailbox::where('email', $current)
                    ->where('is_forwarding_enabled', true)
                    ->where('is_active', true);

                if ($currentMailboxId !== null) {
                    $nextMailboxQuery->where('id', '!=', $currentMailboxId);
                }

                $nextMailbox = $nextMailboxQuery->first();

                // Check if $current has an active alias
                $nextAlias = EmailAlias::where('source_email', $current)
                    ->where('is_active', true)
                    ->first();

                $nextDestinations = [];

                if ($nextMailbox) {
                    $nextDestinations = array_merge($nextDestinations, $nextMailbox->getForwardingDestinationsList());
                }

                if ($nextAlias) {
                    $nextDestinations[] = strtolower(trim($nextAlias->destination_email));
                }

                if (empty($nextDestinations)) {
                    // Reached an external or terminal endpoint; no cycle on this branch
                    break;
                }

                // Check each branch from $current
                $advanced = false;
                foreach ($nextDestinations as $nextTarget) {
                    $nextTarget = strtolower(trim($nextTarget));

                    if ($nextTarget === $source) {
                        $fullPath = array_merge($path, [$nextTarget]);
                        return [
                            'has_cycle'  => true,
                            'cycle_path' => implode(' -> ', $fullPath),
                            'error'      => "Circular forwarding chain detected: " . implode(' -> ', $fullPath),
                        ];
                    }

                    if (isset($visited[$nextTarget])) {
                        $fullPath = array_merge($path, [$nextTarget]);
                        return [
                            'has_cycle'  => true,
                            'cycle_path' => implode(' -> ', $fullPath),
                            'error'      => "Circular forwarding chain detected: " . implode(' -> ', $fullPath),
                        ];
                    }

                    $visited[$nextTarget] = true;
                    $path[] = $nextTarget;
                    $current = $nextTarget;
                    $advanced = true;
                    break; // Follow the first active chain
                }

                if (!$advanced) {
                    break;
                }
            }
        }

        return [
            'has_cycle'  => false,
            'cycle_path' => null,
            'error'      => null,
        ];
    }

    /**
     * Verify and compile mailbox rules telemetry
     */
    public function verifyMailboxRules(Mailbox $mailbox): array
    {
        $destinations = $mailbox->getForwardingDestinationsList();
        $cycleCheck = $this->detectForwardingCycle($mailbox->email, $destinations, $mailbox->id);

        $mtaOperational = app(PostfixService::class)->isPostfixOperational();

        // Forwarding Status
        $forwardingStatus = 'configured';
        if ($mailbox->is_forwarding_enabled) {
            if ($cycleCheck['has_cycle']) {
                $forwardingStatus = 'failed';
            } elseif ($mtaOperational) {
                $forwardingStatus = 'operational';
            } else {
                $forwardingStatus = 'synchronized';
            }
        }

        $sieveScript = $this->compileSieveScript($mailbox);

        return [
            'mailbox_id'  => $mailbox->id,
            'email'       => $mailbox->email,
            'domain_name' => $mailbox->domain?->domain_name,
            'forwarding'  => [
                'is_enabled'      => (bool) $mailbox->is_forwarding_enabled,
                'destinations'    => $destinations,
                'keep_copy'       => (bool) $mailbox->forwarding_keep_copy,
                'is_routable'     => $mailbox->is_forwarding_enabled && !$cycleCheck['has_cycle'] && !empty($destinations),
                'cycle_detected'  => $cycleCheck['has_cycle'],
                'cycle_path'      => $cycleCheck['cycle_path'],
                'status'          => $forwardingStatus,
                'warning'         => $cycleCheck['error'],
            ],
            'auto_reply'  => [
                'is_enabled'           => (bool) $mailbox->auto_reply_enabled,
                'subject'              => $mailbox->auto_reply_subject,
                'body'                 => $mailbox->auto_reply_body,
                'start_at'             => $mailbox->auto_reply_start_at?->toIso8601String(),
                'end_at'               => $mailbox->auto_reply_end_at?->toIso8601String(),
                'schedule_status'      => $mailbox->autoReplyScheduleStatus(),
                'is_currently_active'  => $mailbox->isAutoReplyActive(),
            ],
            'sieve'       => [
                'script_preview'       => $sieveScript,
                'syntax_valid'         => true,
                'driver'               => 'dovecot_sieve_pigeonhole',
                'delivery_transport'   => 'lmtp',
                'environment_mode'     => PHP_OS_FAMILY === 'Linux' ? 'production' : 'local_simulation',
            ],
            'mta'         => [
                'postfix_operational'  => $mtaOperational,
                'map_query'            => 'mysql-virtual-forwardings.cf',
                'status'               => $mtaOperational ? 'operational' : 'synchronized',
            ],
        ];
    }
}
